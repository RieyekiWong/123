for (const entry of ['index.html','index-zh.html']) {
  test(`${entry}: retained evidence survives refresh and a premature reference offers the original login`, async ({ page }) => {
    await investigate(page, entry);
    await close(page);
    await page.reload();
    await expect(page.locator('#story-dialog')).toBeVisible();
    const before = await page.evaluate(() => JSON.parse(localStorage.getItem('stillwater-hotel:v2')).clues);
    expect(before).toEqual(['register']);
    await close(page);
    await page.goto('/'+entry+'#employees?file=letter');
    await expect(page.locator('#employee-form')).toBeVisible();
    await expect(page.locator('#story-dialog')).toBeHidden();
    await page.goto('/'+entry+'#guide?notice=invalid&file=unknown');
    await expect(page.locator('main')).toBeVisible();
    await page.locator('footer [data-action=journal]').click();
    await expect(page.locator('.journal-list li')).toHaveCount(1);
    await expect(page.locator('.journal-missing,.progress-track')).toHaveCount(0);
    await expect(page.locator('dialog [data-room="404"]')).toHaveCount(0);
  });
}

async function seedPage(seed) {
  const p = await browser.newPage({viewport:{width:1280,height:800}});
  await p.addInitScript(recordAudio); await p.clock.install();
  await p.addInitScript(seed => {
    if (localStorage.getItem('xueli-mail-test-seeded')) return;
    localStorage.setItem('stillwater-xueli-sample:v1', JSON.stringify(seed.game));
    localStorage.setItem('stillwater-xueli-chat:v1', JSON.stringify(seed.chat));
    localStorage.setItem('xueli-mail-test-seeded', '1');
  }, seed);
  p.on('pageerror', error => errors.push(error.message));
  await p.goto(page.url()); return p;
}

import { chromium, expect } from '../../node_modules/@playwright/test/index.mjs';
import { BY_ID } from './chapter-data.js';
const browser = await chromium.launch({ executablePath: '/usr/bin/chromium', args: ['--no-sandbox'] });
const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
const errors = [];
page.on('pageerror', error => errors.push(error.message));
await page.goto(process.env.XUELI_URL || 'http://127.0.0.1:3144/design-previews/xueli-21-chapter-01/');
await page.locator('[data-case-language]').click();
await expect(page.locator('#workspace-tabs > span')).toHaveText('Snowley · Local investigation');
await page.locator('#wechat-host .chat-rail [data-case-action=instructions]').click();
await expect(page.locator('.workspace-help')).toContainText('Snowley · Local record');
await page.locator('.workspace-help button').click();
await page.locator('[data-workspace=computer]').click();
await page.locator('.desktop-icon[data-app=files]').click();
await page.locator('[data-open=note]').click();
async function article(id) {
  await expect(page.locator(`.reader[data-document=${id}] .article-body p`)).toHaveText(BY_ID[id].paragraphs.en);
  await expect(page.locator('#root')).not.toContainText('Xueli');
}
await article('note');
await page.locator('[data-open=weekly]').click();
await article('weekly');
await expect(page.locator('.masthead strong')).toHaveText('Snowley Weekly');
await page.evaluate(() => document.fonts.ready);
await page.screenshot({ path: '/tmp/snowley-english-weekly.png' });
await page.locator('#query').fill('Bluebird');
await page.locator('#search-form button').click();
await page.locator('.search-result [data-open=profile]').click();
await article('profile');
await page.locator('#query').fill('June Ward');
await page.locator('#search-form button').click();
await page.locator('.search-result [data-open=reply]').click();
await article('reply');
await expect(page.locator('.mail-headers')).toContainText('J. Ward');
await expect(page.locator('.mail-headers')).toContainText('2023-10-15 17:26');
await page.locator('.desktop-icon[data-app=files]').click();
await page.locator('[data-open=diary]').click();
await article('diary');
await page.locator('.desktop-icon[data-app=browser]').click();
await page.locator('#query').fill('Snowley Weekly');
await page.locator('#search-form button').click();
await expect(page.locator('.search-result')).toHaveCount(3);
await page.locator('.desktop-icon[data-app=casebook]').click();
await expect(page.locator('#place option[value=library]')).toHaveText('Snowley Town Library');
await page.locator('#place').selectOption('library');
await page.locator('[data-action=language]').click();
await expect(page.locator('#workspace-tabs > span')).toHaveText('雪梨镇 · 本机调查');
await expect(page.locator('#place')).toHaveValue('library');
await expect(page.locator('#place option:checked')).toHaveText('雪梨镇图书馆');
await page.reload();
await expect(page.locator('#place')).toHaveValue('library');
console.log(JSON.stringify({ passed: errors.length === 0, articles: ['note','weekly','profile','reply','diary'], checks: 'English rendered paragraphs, Snowley labels and search, language switch, saved choices', errors }));
await browser.close();
if (errors.length) process.exitCode = 1;
